//-----------------------------------------------------------------------------
/*!
   \brief    do controller software reset
*/
//-----------------------------------------------------------------------------
void system_sw_reset(void)
{
   nvs_flash_deinit();
   // if we stop the webserver here we can't call this function from webserver context
// stop_webserver();
   stop_mdns_service();
   wifi_reset();
   io_set_led_off();
   esp_restart();
}
